const dictionaries: Record<Locale, Record<string, string>> = { en, zh };

const interpolate = (template: string, params?: TranslationParams) => {
  if (!params) return template;

  return template.replace(/\{(\w+)\}/g, (match, name) => {
    const value = params[name];
    return value === undefined ? match : String(value);
  });
};

const isLocale = (value: string | null): value is Locale =>
  value === "zh" || value === "en";

const I18nContext = createContext<I18nContextValue | null>(null);

export const I18nProvider = ({ children }: { children: ReactNode }) => {
  const [locale, setLocaleState] = useState<Locale>(DEFAULT_LOCALE);
  const [hasLoadedStoredLocale, setHasLoadedStoredLocale] = useState(false);

  useEffect(() => {
    const storedLocale = window.localStorage.getItem(STORAGE_KEY);
    if (isLocale(storedLocale)) {
      setLocaleState(storedLocale);
    }
    setHasLoadedStoredLocale(true);
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale === "zh" ? "zh-Hans" : "en";
    if (!hasLoadedStoredLocale) {
      return;
    }
    window.localStorage.setItem(STORAGE_KEY, locale);
  }, [hasLoadedStoredLocale, locale]);

  const setLocale = useCallback((nextLocale: Locale) => {
    setLocaleState(nextLocale);
  }, []);

  const t = useCallback((key: string, params?: TranslationParams) => {
    const template = dictionaries[locale][key] ?? dictionaries[DEFAULT_LOCALE][key] ?? key;
    return interpolate(template, params);
  }, [locale]);

  const value = useMemo<I18nContextValue>(() => ({
    locale,
    setLocale,
    t,
  }), [locale, setLocale, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export const useI18n = () => {
  const value = useContext(I18nContext);
  if (!value) {
    throw new Error("useI18n must be used within I18nProvider");
  }

  return value;
};
